"""Regenerate checked-in responsive cover assets with the backend's uv environment.

Run from backend: uv run python ../scripts/prepare_cover_assets.py
The original artwork remains unchanged; runtime builds need no image tooling.
"""
from pathlib import Path
import hashlib
import io
import json

from PIL import Image, ImageOps

root = Path(__file__).resolve().parents[1] / "frontend/public/ui/covers"
output = root / "responsive"
output.mkdir(exist_ok=True)
manifest = {}
for source in sorted(root.glob("cover-*.jpg")):
    with Image.open(source) as image:
        master = ImageOps.exif_transpose(image).convert("RGB")
        manifest[source.stem] = {}
        for width in (160, 320, 640, 1200):
            resized = master.copy()
            resized.thumbnail((width, round(width * master.height / master.width)), Image.Resampling.LANCZOS)
            buffer = io.BytesIO()
            resized.save(buffer, format="WEBP", quality=80 if width <= 320 else 85)
            data = buffer.getvalue()
            digest = hashlib.sha256(data).hexdigest()[:12]
            filename = f"{source.stem}-{digest}-{width}.webp"
            (output / filename).write_bytes(data)
            manifest[source.stem][width] = f"/ui/covers/responsive/{filename}"
# Only remove superseded generated files under this dedicated output directory.
keep = {Path(path).name for variants in manifest.values() for path in variants.values()}
for generated in output.glob("cover-*.webp"):
    if generated.name not in keep and generated.resolve().parent == output.resolve():
        generated.unlink()
(root.parents[2] / "src/coverAssets.ts").write_text("// Generated by scripts/prepare_cover_assets.py; do not edit manually.\nexport const coverAssetVariants = " + json.dumps(manifest, indent=2) + " as const\n", encoding="utf-8")
print(f"Prepared {len(list(output.glob('*.webp')))} responsive cover assets")

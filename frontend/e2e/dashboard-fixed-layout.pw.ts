import { expect, test } from '@playwright/test'
import { openBookshelf } from './dashboardFixture'

for (const viewport of [{ width: 1920, height: 1080 }, { width: 1440, height: 900 }, { width: 1280, height: 720 }, { width: 1062, height: 660 }, { width: 390, height: 844 }])
test(`bookshelf stays fixed and keeps all shelves reachable at ${viewport.width}x${viewport.height}`, async ({ page }) => {
  await page.setViewportSize(viewport)
  await openBookshelf(page)
  const canvas = page.locator('.dashboard-canvas')
  for (const selector of ['.recent-card', '.novel-card', '.collection-card', '.dashboard-search']) {
    const box = await page.locator(selector).first().boundingBox()
    expect(box!.y).toBeGreaterThanOrEqual(0)
    expect(box!.y + box!.height).toBeLessThanOrEqual(viewport.height)
  }
  expect(await canvas.evaluate(element => (element as HTMLElement).offsetWidth - element.clientWidth)).toBe(0)
  expect(await page.evaluate(() => document.documentElement.scrollHeight - innerHeight)).toBe(0)
  expect(await canvas.evaluate(element => element.scrollWidth - element.clientWidth)).toBe(0)
  const greeting = await page.locator('.dashboard-greeting').boundingBox()
  await page.locator('.recent-card').first().focus()
  await page.keyboard.press('PageDown')
  await canvas.hover({ position: { x: 12, y: 360 } })
  await page.mouse.wheel(0, 900)
  // A real wheel event has been delivered; inspect the settled layout afterwards.
  await expect(canvas).toHaveCSS('overflow-y', 'clip')
  expect(await canvas.evaluate(element => element.scrollTop)).toBe(0)
  expect(await page.locator('.dashboard-greeting').boundingBox()).toEqual(greeting)
  const collection = page.getByRole('button', { name: 'Open 设定集布局样例 setting collection' })
  await expect(collection).toBeInViewport()
  await collection.focus()
  await expect(collection).toBeFocused()
  await expect(collection).toBeInViewport()
  expect(await canvas.evaluate(element => element.scrollTop)).toBe(0)
  const next = page.getByRole('button', { name: 'Show more novels' })
  await next.click()
  await expect.poll(() => page.locator('.novels-row').evaluate(element => element.scrollLeft)).toBeGreaterThan(0)
  expect(await canvas.evaluate(element => element.scrollTop)).toBe(0)
  await page.getByRole('button', { name: '新建作品', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '创建作品' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollHeight - innerHeight)).toBe(0)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: '创建作品' })).not.toBeVisible()
  await openBookshelf(page, false)
  expect(await canvas.evaluate(element => (element as HTMLElement).offsetWidth - element.clientWidth)).toBe(0)
  await expect(page.getByRole('button', { name: '创建第一部作品' })).toBeVisible()
})

import { expect, test } from '@playwright/test'

// HTTP fixtures isolate layout and keyboard behavior; they are not backend acceptance.
test('bookshelf restores the desktop composition and offers a compact empty state', async ({ page }) => {
  await page.route('**/api/v1/projects', route => route.fulfill({ json: [] }))
  await page.route('**/api/v1/setting-collections', route => route.fulfill({ json: [] }))
  await page.setViewportSize({ width: 1440, height: 1024 })
  await page.goto('/')
  const greeting = page.getByRole('heading', { level: 1 })
  const bounds = await greeting.boundingBox()
  expect(bounds!.y).toBeGreaterThanOrEqual(150)
  expect(bounds!.y).toBeLessThanOrEqual(220)
  const firstNovel = page.getByRole('button', { name: '创建第一部作品' })
  await expect(firstNovel).toBeVisible()
  await page.setViewportSize({ width: 1280, height: 720 })
  await firstNovel.click()
  const novel = page.getByRole('dialog', { name: '创建作品', exact: true })
  await expect(novel.getByLabel('标题', { exact: true })).toBeFocused()
  expect(await novel.evaluate(el => el.scrollHeight <= el.clientHeight)).toBe(true)
  await expect(novel.getByLabel('封面地址或预设（可选）')).not.toBeVisible()
  await novel.getByText('更多作品信息', { exact: true }).click()
  await expect(novel.getByLabel('封面地址或预设（可选）')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(firstNovel).toBeFocused()

  await page.setViewportSize({ width: 820, height: 600 })
  await page.getByRole('button', { name: '新建设定集', exact: true }).click()
  const collection = page.getByRole('dialog', { name: '新建设定集', exact: true })
  await expect(collection.getByLabel('标题', { exact: true })).toBeFocused()
  await expect(collection.getByLabel('设定集标识')).not.toBeVisible()
  await page.keyboard.press('Shift+Tab')
  await expect(collection.getByRole('button', { name: '关闭新建设定集' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: '新建设定集', exact: true })).toBeFocused()
  await page.getByRole('searchbox', { name: '搜索作品' }).focus()
  await expect(page.getByRole('searchbox', { name: '搜索作品' })).toBeInViewport()
})

test('collection submission resists dismissal and retains text after a server failure', async ({ page }) => {
  let release!: () => void
  const responseReady = new Promise<void>(resolve => { release = resolve })
  let writes = 0
  await page.route('**/api/v1/projects', route => route.fulfill({ json: [] }))
  await page.route('**/api/v1/setting-collections', async route => {
    if (route.request().method() === 'GET') return route.fulfill({ json: [] })
    writes++
    await responseReady
    return route.fulfill({ status: 503, json: { detail: 'Temporary failure' } })
  })
  await page.goto('/')
  await page.getByRole('button', { name: '新建设定集', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新建设定集', exact: true })
  await dialog.getByLabel('标题', { exact: true }).fill('雾港设定')
  await dialog.getByRole('button', { name: '新建设定集', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '正在创建设定集…' })).toBeDisabled()
  await page.keyboard.press('Escape')
  await page.mouse.click(8, 8)
  await expect(dialog).toBeVisible()
  expect(writes).toBe(1)
  release()
  await expect(dialog.getByRole('alert')).toBeFocused()
  await expect(dialog.getByLabel('标题', { exact: true })).toHaveValue('雾港设定')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('button', { name: '新建设定集', exact: true })).toBeFocused()
})

test('populated shelves and long creation forms remain reachable in short windows', async ({ page }) => {
  const stamp = '2026-10-16T00:00:00Z'
  const projects = Array.from({ length: 7 }, (_, index) => ({ id: `novel-${index}`, title: `作品 ${index + 1}`, slug: `novel-${index}`, genre: null, target_platform: null, status: 'draft', workspace_root: `workspaces/novel-${index}`, metadata: {}, created_at: stamp, updated_at: stamp }))
  const collections = Array.from({ length: 5 }, (_, index) => ({ id: `collection-${index}`, title: `设定 ${index + 1}`, slug: `collection-${index}`, description: null, status: 'active', owner_id: null, workspace_root: `settings/collection-${index}`, revision: 1, metadata: {}, created_at: stamp, updated_at: stamp }))
  await page.route('**/api/v1/projects', route => route.fulfill({ json: projects }))
  await page.route('**/api/v1/setting-collections', route => route.fulfill({ json: collections }))
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Open 作品 1', exact: true }).first()).toBeVisible()
  const recent = await page.getByRole('region', { name: '最近创作', exact: true }).boundingBox()
  const novels = await page.getByRole('region', { name: '作品', exact: true }).boundingBox()
  const settings = await page.getByRole('region', { name: '设定集', exact: true }).boundingBox()
  expect(novels!.y).toBeGreaterThan(recent!.y + recent!.height)
  expect(settings!.y).toBeGreaterThan(novels!.y + novels!.height)
  await page.setViewportSize({ width: 820, height: 600 })
  const collectionCard = page.getByRole('button', { name: 'Open 设定 1 setting collection' })
  await collectionCard.scrollIntoViewIfNeeded()
  await expect(collectionCard).toBeInViewport()
  await page.getByRole('button', { name: '新建作品', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '创建作品', exact: true })
  await dialog.getByText('更多作品信息', { exact: true }).click()
  await dialog.getByText('高级选项：作品标识', { exact: true }).click()
  const slug = dialog.getByLabel('Slug', { exact: true })
  await slug.fill('short-window')
  await expect(slug).toBeInViewport()
  const submit = dialog.getByRole('button', { name: '创建作品', exact: true })
  await submit.scrollIntoViewIfNeeded()
  await expect(submit).toBeInViewport()
  await page.setViewportSize({ width: 390, height: 600 })
  await expect(submit).toBeInViewport()
  const bounds = await dialog.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
})

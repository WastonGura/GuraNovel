import { expect, test } from '@playwright/test'
import { openBookshelf } from './dashboardFixture'

test('metadata rows have even spacing and label chips match the add control', async ({ page }) => {
  await page.route('**/api/v1/projects/novel-0/chapters', route => route.fulfill({ json: [] }))
  await openBookshelf(page)
  await page.locator('.novel-card').first().click()
  const dialog = page.locator('dialog.novel-dialog')
  await dialog.getByRole('button', { name: '编辑资料', exact: true }).click()
  const chapter = await dialog.getByLabel('章节：0', { exact: true }).boundingBox()
  const label = await dialog.locator('.novel-property-label').boundingBox()
  expect(label!.y - chapter!.y - chapter!.height).toBeLessThanOrEqual(14)
  await dialog.getByRole('button', { name: '添加标签', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '添加标签', exact: true })
  await picker.getByRole('button', { name: '奇幻', exact: true }).click()
  await page.keyboard.press('Escape')
  const chip = await dialog.getByRole('button', { name: '删除标签：奇幻', exact: true }).boundingBox()
  const add = await dialog.getByRole('button', { name: '添加标签', exact: true }).boundingBox()
  expect(chip!.height).toBe(add!.height)
  expect(chip!.width).toBe(add!.width)
  const border = await dialog.locator('.novel-metadata-more').evaluate(el => getComputedStyle(el).borderTopWidth)
  expect(border).toBe('0px')
})

test('collection and cover choices preview immediately, autosave and update bookshelf artwork', async ({ page }) => {
  const writes: Array<Record<string, unknown>> = []
  let stored = { id: 'novel-0', slug: 'novel-0', genre: null, target_platform: null, setting_collection_id: null, status: 'active', workspace_root: '',
    created_at: '2026-10-19T00:00:00Z', updated_at: '2026-10-19T00:00:00Z' } as Record<string, unknown>
  await page.route('**/api/v1/projects/novel-0/chapters', route => route.fulfill({ json: [] }))
  await page.route('**/api/v1/projects/novel-0', async route => {
    const payload = route.request().postDataJSON()
    writes.push(payload)
    stored = { ...stored, ...payload }
    await route.fulfill({ json: stored })
  })
  await openBookshelf(page)
  await page.locator('.novel-card').first().click()
  const dialog = page.locator('dialog.novel-dialog')
  await dialog.getByRole('button', { name: '编辑资料', exact: true }).click()
  await dialog.getByText('更多作品信息', { exact: true }).click()
  await dialog.getByRole('button', { name: '选择设定集', exact: true }).click()
  const collections = page.getByRole('dialog', { name: '选择设定集', exact: true })
  await collections.getByRole('textbox', { name: '搜索设定集', exact: true }).fill('布局')
  await collections.getByRole('button', { name: '设定集布局样例', exact: true }).click()
  await expect(collections).not.toBeVisible()
  await expect(dialog.getByRole('button', { name: '选择设定集', exact: true })).toContainText('设定集布局样例')
  await expect.poll(() => writes.at(-1)?.setting_collection_id).toBe('world')
  await dialog.getByRole('button', { name: '更换封面', exact: true }).click()
  const covers = page.getByRole('dialog', { name: '更换封面', exact: true })
  await covers.getByRole('button', { name: '封面 6', exact: true }).click()
  await expect(covers).not.toBeVisible()
  await expect(dialog.locator('.novel-cover-preview img')).toHaveAttribute('src', '/ui/covers/cover-6.jpg')
  await expect.poll(() => (writes.at(-1)?.metadata as Record<string, unknown>)?.cover).toBe('cover-6.jpg')
  await dialog.getByRole('button', { name: '关闭作品详情', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.locator('.novel-card').first().locator('img')).toHaveAttribute('src', '/ui/covers/cover-6.jpg')
  await page.locator('.novel-card').first().click()
  await expect(dialog.locator('.novel-cover-preview img')).toHaveAttribute('src', '/ui/covers/cover-6.jpg')
  await dialog.getByRole('button', { name: '更换封面', exact: true }).click()
  await page.getByRole('dialog', { name: '更换封面', exact: true }).getByRole('button', { name: '默认封面', exact: true }).click()
  await expect(dialog.getByRole('img', { name: '默认封面' })).toBeVisible()
  await expect.poll(() => (writes.at(-1)?.metadata as Record<string, unknown>)?.cover).toBe('cover-default')
  await dialog.getByRole('button', { name: '关闭作品详情', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.locator('.novel-card').first().getByRole('img', { name: '默认封面' })).toBeVisible()
})

test('cover and collection pickers cancel cleanly and keep short-window controls reachable', async ({ page }) => {
  await page.setViewportSize({ width: 820, height: 600 })
  let writes = 0
  await page.route('**/api/v1/projects/novel-0/chapters', route => route.fulfill({ json: [] }))
  await page.route('**/api/v1/projects/novel-0', async route => { writes++; await route.fulfill({ status: 503, json: { detail: 'offline' } }) })
  await page.route('https://images.example.test/broken.jpg', route => route.fulfill({ status: 404, body: '' }))
  await openBookshelf(page)
  await page.locator('.novel-card').first().click()
  const dialog = page.locator('dialog.novel-dialog')
  await dialog.getByRole('button', { name: '更换封面', exact: true }).click()
  const covers = page.getByRole('dialog', { name: '更换封面', exact: true })
  await expect(covers.getByRole('button', { name: '封面 1', exact: true })).toBeInViewport({ ratio: 1 })
  await expect(covers.getByRole('button', { name: '封面 8', exact: true })).toBeInViewport({ ratio: 1 })
  await expect(covers.getByRole('button', { name: '使用图片', exact: true })).toBeInViewport({ ratio: 1 })
  await covers.getByRole('textbox', { name: '封面图片链接', exact: true }).fill('https://images.example.test/broken.jpg')
  await covers.getByRole('button', { name: '使用图片', exact: true }).click()
  await expect(covers.getByRole('alert')).toContainText('图片无法加载')
  expect(writes).toBe(0)
  await page.keyboard.press('Escape')
  await expect(covers).not.toBeVisible()
  await expect(dialog.getByRole('button', { name: '更换封面', exact: true })).toBeFocused()
  await expect(dialog.locator('.novel-cover-preview img')).toHaveAttribute('src', '/ui/covers/cover-1.jpg')
  await dialog.getByRole('button', { name: '编辑资料', exact: true }).click()
  await dialog.getByText('更多作品信息', { exact: true }).click()
  await dialog.getByRole('button', { name: '选择设定集', exact: true }).click()
  const collections = page.getByRole('dialog', { name: '选择设定集', exact: true })
  await collections.getByRole('textbox', { name: '搜索设定集', exact: true }).fill('找不到的世界')
  await expect(collections.getByText('没有找到匹配的设定集')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog.getByRole('button', { name: '选择设定集', exact: true })).toBeFocused()
  expect(writes).toBe(0)
})

test('a validated custom cover URL previews and uses the same automatic metadata save', async ({ page }) => {
  let savedCover: unknown
  await page.route('https://images.example.test/novel.jpg', route => route.fulfill({ path: 'public/ui/covers/cover-8.jpg' }))
  await page.route('**/api/v1/projects/novel-0/chapters', route => route.fulfill({ json: [] }))
  await page.route('**/api/v1/projects/novel-0', async route => {
    savedCover = route.request().postDataJSON().metadata.cover
    await route.fulfill({ status: 503, json: { detail: 'offline' } })
  })
  await openBookshelf(page)
  await page.locator('.novel-card').first().click()
  const dialog = page.locator('dialog.novel-dialog')
  await dialog.getByRole('button', { name: '更换封面', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '更换封面', exact: true })
  await picker.getByRole('textbox', { name: '封面图片链接', exact: true }).fill('https://images.example.test/novel.jpg')
  await picker.getByRole('button', { name: '使用图片', exact: true }).click()
  await expect(picker).not.toBeVisible()
  await expect(dialog.locator('.novel-cover-preview img')).toHaveAttribute('src', 'https://images.example.test/novel.jpg')
  await expect.poll(() => savedCover).toBe('https://images.example.test/novel.jpg')
  await expect(dialog.getByRole('alert')).toContainText('已保留修改')
})

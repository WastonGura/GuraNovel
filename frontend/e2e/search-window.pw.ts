import { expect, test } from '@playwright/test'
import { openBookshelf } from './dashboardFixture'

test('toolbar search replaces the bottom bar and the raised bookshelf stays fixed', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1024 })
  await openBookshelf(page)
  expect((await page.getByRole('heading', { level: 1 }).boundingBox())!.y).toBeLessThan(140)
  await expect(page.locator('.dashboard-search')).toHaveCount(0)
  await expect(page.getByRole('searchbox')).toHaveCount(0)
  const trigger = page.getByRole('button', { name: '搜索', exact: true })
  const bounds = (await trigger.boundingBox())!
  expect(bounds.x).toBeLessThan(110)
  expect(bounds.y).toBeLessThan(50)
  await page.mouse.move(900, 950)
  await page.mouse.wheel(0, 600)
  expect(await page.evaluate(() => window.scrollY)).toBe(0)
  expect((await page.getByRole('heading', { level: 1 }).boundingBox())!.y).toBeLessThan(140)
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: '搜索', exact: true })
  await expect(dialog.getByRole('searchbox')).toBeFocused()
  await expect(dialog.getByRole('region', { name: '预览' })).toContainText('作品 1')
  await expect.poll(() => dialog.evaluate(el => el.getAnimations().some(animation => animation.playState === 'running'))).toBe(false)
  const list = await dialog.locator('.search-window-results').boundingBox()
  const preview = await dialog.getByRole('region', { name: '预览' }).boundingBox()
  expect(preview!.x).toBeGreaterThan(list!.x + list!.width)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveClass(/is-closing/)
  await expect(dialog).not.toBeAttached()
  await expect(trigger).toBeFocused()
})

test('search supports type filters, empty recovery and keyboard preview before opening', async ({ page }) => {
  await page.route('**/api/v1/projects/novel-1/chapters', route => route.fulfill({ json: [] }))
  await openBookshelf(page)
  await page.keyboard.press('Control+k')
  const dialog = page.getByRole('dialog', { name: '搜索', exact: true })
  const input = dialog.getByRole('searchbox')
  await dialog.getByRole('button', { name: '设定集', exact: true }).click()
  await expect(dialog.locator('.search-choice')).toHaveCount(1)
  await expect(dialog.getByRole('region', { name: '预览' })).toContainText('设定集布局样例')
  await input.fill('不存在')
  await expect(dialog.getByRole('status')).toContainText('没有找到')
  await expect(dialog.locator('.search-choice')).toHaveCount(0)
  await expect(dialog.getByRole('region', { name: '预览' })).not.toContainText('设定集布局样例')
  await dialog.getByRole('button', { name: '作品', exact: true }).click()
  await input.fill('作品')
  await input.press('ArrowDown')
  await expect(dialog.locator('.search-choice').first()).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(dialog.locator('.search-choice').nth(1)).toBeFocused()
  await expect(dialog.getByRole('region', { name: '预览' })).toContainText('作品 2')
  await page.keyboard.press('Enter')
  await expect(dialog).not.toBeAttached()
  await expect(page.locator('dialog.novel-dialog')).toBeVisible()
  await expect(page).toHaveURL(/project=novel-1/)
})

test('search is usable in a narrow short window without scrolling the page', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 600 })
  await openBookshelf(page)
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '搜索', exact: true })
  const input = dialog.getByRole('searchbox')
  await expect(input).toBeFocused()
  await expect(dialog.getByRole('region', { name: '预览' })).not.toBeVisible()
  await expect.poll(() => dialog.evaluate(el => el.getAnimations().some(animation => animation.playState === 'running'))).toBe(false)
  const bounds = (await dialog.boundingBox())!
  expect(bounds.x).toBeGreaterThanOrEqual(0)
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(390)
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(600)
  await dialog.locator('.search-choice').last().scrollIntoViewIfNeeded()
  await expect(dialog.locator('.search-choice').last()).toBeInViewport()
  expect(await page.evaluate(() => window.scrollY)).toBe(0)
  await expect(input).toBeInViewport()
})

test('failed content remains distinct from an empty search', async ({ page }) => {
  await page.route('**/api/v1/projects', route => route.fulfill({ status: 503, json: { detail: 'unavailable' } }))
  await page.route('**/api/v1/setting-collections', route => route.fulfill({ json: [] }))
  await page.goto('/')
  await expect(page.getByRole('alert')).toBeVisible()
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '搜索', exact: true })
  await expect(dialog.getByRole('status')).toContainText('加载失败')
  await dialog.getByRole('button', { name: '设定集', exact: true }).click()
  await expect(dialog.getByRole('status')).toHaveText('还没有作品或设定集')
})

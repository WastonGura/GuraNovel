import { expect, test } from '@playwright/test'

test('Gura resizes width and height independently, keeps the current minimum and remembers the preference', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/preview/studio')
  await page.getByRole('button', { name: 'Gura', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: '与 Gura 对话', exact: true })
  await expect(drawer).toBeVisible()
  await expect(page.getByLabel('给 Gura 的消息')).toBeFocused()
  const container = page.getByRole('complementary', { name: 'Gura 助手' })
  await expect.poll(async () => (await container.boundingBox())!.width).toBeCloseTo(320, 0)
  const initial = (await container.boundingBox())!
  const widthHandle = page.getByRole('separator', { name: '调整 Gura 宽度', exact: true })
  await widthHandle.focus()
  await widthHandle.press('ArrowLeft')
  await expect.poll(async () => (await container.boundingBox())!.width).toBeCloseTo(initial.width + 10, 0)
  expect((await container.boundingBox())!.height).toBeCloseTo(initial.height, 0)
  const heightHandle = page.getByRole('separator', { name: '调整 Gura 高度', exact: true })
  await heightHandle.focus()
  await heightHandle.press('Shift+ArrowUp')
  await expect.poll(async () => (await container.boundingBox())!.height).toBeCloseTo(initial.height + 40, 0)
  const enlarged = (await container.boundingBox())!
  await page.getByLabel('给 Gura 的消息').fill('调节大小时保留这段输入')
  await page.reload()
  await expect(drawer).toBeVisible()
  await expect.poll(async () => (await container.boundingBox())!.width).toBeCloseTo(enlarged.width, 0)
  await expect.poll(async () => (await container.boundingBox())!.height).toBeCloseTo(enlarged.height, 0)
  await expect(page.getByLabel('给 Gura 的消息')).toHaveValue('调节大小时保留这段输入')
  await page.getByRole('separator', { name: '调整 Gura 宽度', exact: true }).dblclick()
  await expect.poll(async () => (await container.boundingBox())!.width).toBeCloseTo(initial.width, 0)
  await expect.poll(async () => (await container.boundingBox())!.height).toBeCloseTo(initial.height, 0)
  await widthHandle.focus()
  await widthHandle.press('ArrowRight')
  await heightHandle.focus()
  await heightHandle.press('ArrowDown')
  await expect.poll(async () => (await container.boundingBox())!.width).toBeCloseTo(initial.width, 0)
  expect((await container.boundingBox())!.height).toBeCloseTo(initial.height, 0)
})

test('pointer resizing stops at the panel limits and restores them after the viewport grows', async ({ page }) => {
  await page.setViewportSize({ width: 1200, height: 900 })
  await page.goto('/preview/studio')
  await page.getByRole('button', { name: 'Gura', exact: true }).click()
  await expect(page.getByLabel('给 Gura 的消息')).toBeFocused()
  const handle = page.getByRole('button', { name: '调整 Gura 大小', exact: true })
  const corner = (await handle.boundingBox())!
  await page.mouse.move(corner.x + corner.width / 2, corner.y + corner.height / 2)
  await page.mouse.down()
  await page.mouse.move(-300, -300)
  const panel = page.getByRole('complementary', { name: 'Gura 助手' })
  const expanded = (await panel.boundingBox())!
  expect(expanded.x).toBeGreaterThanOrEqual(16)
  expect(expanded.y).toBeGreaterThanOrEqual(16)
  expect(expanded.width).toBeCloseTo(540, 0)
  expect(expanded.height).toBeCloseTo(720, 0)
  await page.mouse.up()
  await page.mouse.move(900, 800)
  const finished = (await panel.boundingBox())!
  expect(finished.width).toBeCloseTo(expanded.width, 0)
  expect(finished.height).toBeCloseTo(expanded.height, 0)
  expect(await page.evaluate(() => document.documentElement.scrollHeight - innerHeight)).toBe(0)
  await page.setViewportSize({ width: 820, height: 600 })
  await expect.poll(async () => (await panel.boundingBox())!.y).toBeGreaterThanOrEqual(16)
  await expect.poll(async () => (await panel.boundingBox())!.width).toBeCloseTo(369, 0)
  await expect.poll(async () => (await panel.boundingBox())!.height).toBeCloseTo(480, 0)
  expect((await panel.boundingBox())!.x).toBeGreaterThanOrEqual(16)
  await page.setViewportSize({ width: 1200, height: 900 })
  await expect.poll(async () => (await panel.boundingBox())!.width).toBeCloseTo(expanded.width, 0)
  await expect.poll(async () => (await panel.boundingBox())!.height).toBeCloseTo(expanded.height, 0)
})

test('a narrow viewport keeps the original minimum instead of squeezing the panel to 45 percent', async ({ page }) => {
  await page.setViewportSize({ width: 600, height: 650 })
  await page.goto('/preview/studio')
  await page.getByRole('button', { name: 'Gura', exact: true }).click()
  await expect(page.getByLabel('给 Gura 的消息')).toBeFocused()
  const widthHandle = page.getByRole('separator', { name: '调整 Gura 宽度', exact: true })
  const heightHandle = page.getByRole('separator', { name: '调整 Gura 高度', exact: true })
  await widthHandle.focus()
  await widthHandle.press('Shift+ArrowLeft')
  for (let count = 0; count < 5; count++) await heightHandle.press('Shift+ArrowUp')
  const panel = page.getByRole('complementary', { name: 'Gura 助手' })
  await expect.poll(async () => (await panel.boundingBox())!.width).toBeCloseTo(320, 0)
  await expect.poll(async () => (await panel.boundingBox())!.height).toBeCloseTo(520, 0)
  const box = (await panel.boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(16)
  expect(box.y).toBeGreaterThanOrEqual(16)
})

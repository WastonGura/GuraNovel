import { expect, test } from '@playwright/test'
import { openBookshelf } from './dashboardFixture'

for (const viewport of [{ width: 1440, height: 900 }, { width: 1062, height: 660 }, { width: 820, height: 600 }]) {
  test(`unified novel dialog keeps the cover and actions fixed at ${viewport.width}x${viewport.height}`, async ({ page }) => {
    await page.setViewportSize(viewport)
    const chapters = Array.from({ length: 40 }, (_, index) => ({ id: `chapter-${index}`, project_id: 'novel-0', chapter_number: index + 1, title: `章节 ${index + 1}：一个较长的章节标题`, metadata: {}, status: 'draft', current_outline_document_id: null, current_draft_document_id: null, final_document_id: null, summary_document_id: null, word_count: 0, created_at: '2026-10-18T00:00:00Z', updated_at: '2026-10-18T00:00:00Z' }))
    await page.route('**/api/v1/projects/novel-0/chapters', route => route.fulfill({ json: chapters }))
    await openBookshelf(page)
    const trigger = page.locator('.novel-card').first()
    await trigger.click()
    const dialog = page.getByRole('dialog')
    await expect(dialog.getByRole('tablist')).toHaveCount(0)
    await expect(dialog.getByRole('button', { name: /第40话 / })).toBeVisible()
    await dialog.evaluate(async element => { await Promise.all(element.getAnimations().map(animation => animation.finished)) })
    const cover = dialog.locator('.novel-cover-preview')
    const bounds = await cover.boundingBox()
    const panel = await dialog.locator('.novel-view-panel').first().boundingBox()
    expect(bounds!.x + bounds!.width).toBeLessThan(panel!.x)
    expect(bounds!.width).toBeGreaterThanOrEqual(viewport.width >= 1062 ? 260 : 180)
    expect(await dialog.evaluate(el => el.scrollHeight - el.clientHeight)).toBe(0)
    const action = dialog.getByRole('button', { name: '开始创作', exact: true })
    const actionBounds = await action.boundingBox()
    const scroll = dialog.locator('.novel-panel-scroll').first()
    await scroll.hover()
    await page.mouse.wheel(0, 4000)
    await expect.poll(() => scroll.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
    expect(await cover.boundingBox()).toEqual(bounds)
    expect(await action.boundingBox()).toEqual(actionBounds)
    await expect(dialog.getByRole('button', { name: /第1话 / })).toBeInViewport()
    await dialog.getByRole('button', { name: '编辑资料', exact: true }).click()
    await expect(dialog.getByLabel('编辑简介')).toHaveValue('')
    await expect(dialog.getByLabel('章节：40', { exact: true })).toBeVisible()
    await dialog.getByRole('button', { name: '章节目录', exact: true }).click()
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()

    await page.getByRole('button', { name: '新建作品', exact: true }).click()
    const create = page.getByRole('dialog', { name: '创建作品', exact: true })
    await create.getByLabel('标题', { exact: true }).fill('新故事的标题')
    await expect(create.locator('.novel-cover-caption')).toHaveText('新故事的标题')
    const createCover = await create.locator('.novel-cover-preview').boundingBox()
    expect(createCover!.width).toBeGreaterThanOrEqual(viewport.width >= 1062 ? 260 : 180)
    await create.getByText('更多作品信息', { exact: true }).click()
    await expect(create.getByRole('button', { name: '创建作品', exact: true })).toBeInViewport()
    expect(await create.evaluate(el => el.scrollHeight - el.clientHeight)).toBe(0)
    expect(await page.evaluate(() => document.documentElement.scrollHeight - innerHeight)).toBe(0)
  })
}

test('automatic metadata saves keep newer input and recover from a failed request', async ({ page }) => {
  let release!: () => void
  const pending = new Promise<void>(resolve => { release = resolve })
  const writes: string[] = []
  await page.route('**/api/v1/projects/novel-0/chapters', route => route.fulfill({ json: [] }))
  await page.route('**/api/v1/projects/novel-0', async route => {
    writes.push(route.request().postDataJSON().title)
    if (writes.length === 1) await pending
    return route.fulfill({ status: 503, json: { detail: 'offline' } })
  })
  await openBookshelf(page)
  await page.locator('.novel-card').first().click()
  const dialog = page.locator('dialog.novel-dialog')
  await dialog.getByRole('button', { name: '编辑资料', exact: true }).click()
  const title = dialog.getByLabel('编辑标题')
  await title.fill('第一个标题')
  await expect(dialog.locator('.novel-cover-caption')).toHaveText('第一个标题')
  await expect.poll(() => writes.length).toBe(1)
  await expect(title).toBeEnabled()
  await title.fill('还没有保存的书名')
  await expect(dialog.locator('.novel-cover-caption')).toHaveText('还没有保存的书名')
  release()
  await expect(dialog.getByRole('alert')).toBeVisible()
  await expect(title).toHaveValue('还没有保存的书名')
  await dialog.getByRole('button', { name: '章节目录', exact: true }).click()
  await dialog.getByRole('button', { name: '编辑资料', exact: true }).click()
  await expect(title).toHaveValue('还没有保存的书名')
  await dialog.getByRole('button', { name: '重试同步', exact: true }).click()
  await expect.poll(() => writes.length).toBeGreaterThanOrEqual(2)
  expect(writes.at(-1)).toBe('还没有保存的书名')
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeAttached()
  await page.locator('.novel-card').first().click()
  await dialog.getByRole('button', { name: '编辑资料', exact: true }).click()
  await expect(dialog.getByLabel('编辑标题')).toHaveValue('还没有保存的书名')
})

test('short-window editing gives priority to title, tags and introduction', async ({ page }) => {
  await page.setViewportSize({ width: 1062, height: 660 })
  await page.route('**/api/v1/projects/novel-0/chapters', route => route.fulfill({ json: [] }))
  await openBookshelf(page)
  await page.locator('.novel-card').first().click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: '编辑资料', exact: true }).click()
  await expect(dialog.getByRole('group', { name: '作品标签' })).toBeInViewport({ ratio: 1 })
  await expect(dialog.getByLabel('编辑简介')).toBeInViewport({ ratio: 1 })
  await expect(dialog.getByLabel('编辑题材')).not.toBeVisible()
  await expect(dialog.getByRole('button', { name: '开始创作', exact: true })).toBeInViewport()
  const titleSize = await dialog.getByLabel('编辑标题').evaluate(element => parseFloat(getComputedStyle(element).fontSize))
  expect(titleSize).toBeGreaterThanOrEqual(28)
  expect(titleSize).toBeLessThanOrEqual(32)
})

import { expect, test, type Page } from '@playwright/test'

const collectionId = 'c1111111-1111-4111-8111-111111111111'
const docId = 'd1111111-1111-4111-8111-111111111111'
const worldId = 'd2222222-2222-4222-8222-222222222222'
const stamp = '2026-10-20T00:00:00Z'

async function workspace(page: Page) {
  const state = { content: '看', version: 1, writes: [] as string[] }
  const version = () => `v1111111-1111-4111-8111-${String(state.version).padStart(12, '0')}`
  await page.route('**/api/v1/**', async route => {
    const path = new URL(route.request().url()).pathname
    const json = (value: unknown) => route.fulfill({ json: value })
    if (path === `/api/v1/setting-collections/${collectionId}`) return json({ id: collectionId, title: '引用测试设定集', slug: 'references', owner_id: null, description: null, status: 'active', workspace_root: '/tmp/references', revision: 1, metadata: {}, created_at: stamp, updated_at: stamp })
    if (path.endsWith('/projects') || path === '/api/v1/setting-collections') return json([])
    if (path.endsWith('/documents')) return json([docId, worldId].map((id, index) => ({ id, project_id: null, chapter_id: null, setting_collection_id: collectionId, title: index ? '世界观' : '角色', path: `${id}.md`, type: index ? 'world_overview' : 'character_profile', current_version_id: version(), current_version: null, metadata: { category: index ? 'world' : 'setting' }, created_at: stamp, updated_at: stamp })))
    if (path === `/api/v1/documents/${docId}/content`) {
      if (route.request().method() === 'PUT') {
        const payload = route.request().postDataJSON()
        expect(payload.expected_current_version_id).toBe(version())
        const parent = version(); state.version++; state.content = payload.content; state.writes.push(payload.content)
        return json({ id: version(), document_id: docId, version_number: state.version, parent_version_id: parent, source: 'user', actor_user_id: null, agent_role: null, workflow_run_id: null, content_hash: 'hash', byte_size: state.content.length, word_count: state.content.length, file_path: 'role.md', change_summary: null, created_at: stamp })
      }
      return json({ document_id: docId, version_id: version(), content: state.content })
    }
    if (path === `/api/v1/documents/${worldId}/content`) return json({ document_id: worldId, version_id: version(), content: '这是被引用的世界观正文。' })
    return json([])
  })
  await page.goto(`/setting-collections/${collectionId}?note=${docId}&category=setting&mode=note`)
  await expect(page.getByLabel('设定正文', { exact: true })).toHaveText('看')
  return state
}

test('only @ opens reference suggestions; chosen references stay decorated through typing, save and reload', async ({ page }) => {
  const state = await workspace(page)
  const editor = page.getByLabel('设定正文', { exact: true })
  await expect(page.getByRole('button', { name: /引用条目/ })).toHaveCount(0)
  await editor.click(); await page.keyboard.press('Control+End')
  await page.keyboard.press('Control+Space')
  await expect(page.getByRole('listbox', { name: '引用条目建议' })).toHaveCount(0)
  await editor.fill('看[[')
  await expect(page.getByRole('listbox', { name: '引用条目建议' })).toHaveCount(0)
  await editor.fill('看@世')
  await page.getByRole('option', { name: '世界观', exact: true }).click()
  const reference = editor.locator('[data-reference-title="世界观"]')
  await expect(reference).toBeVisible()
  await expect(editor).not.toContainText('[[')
  await expect(reference.locator('sup')).toHaveCount(0)
  await expect(reference).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await expect(reference).toHaveCSS('color', 'rgb(102, 102, 102)')
  await page.keyboard.type('，还有其他规则。')
  await expect(editor).toContainText('看世界观')
  await expect.poll(() => state.content).toBe('看[[世界观]]，还有其他规则。')
  await page.reload()
  await expect(reference).toBeVisible()
  await expect(editor).not.toContainText('[[')
  await editor.click(); await page.keyboard.press('Control+End')
  await page.keyboard.press('Enter'); await page.keyboard.type('下一段。')
  await expect.poll(() => state.content).toBe('看[[世界观]]，还有其他规则。\n下一段。')
  await reference.click({ modifiers: ['Control'] })
  await expect(page.getByLabel('设定标题')).toHaveValue('世界观')
  await expect(editor).toHaveText('这是被引用的世界观正文。')
})

test('a reference deletes as one unit and typing undo does not expose its brackets', async ({ page }) => {
  const state = await workspace(page)
  const editor = page.getByLabel('设定正文', { exact: true })
  await editor.fill('看@世')
  await page.getByRole('option', { name: '世界观', exact: true }).click()
  await expect(editor.locator('[data-reference-title]')).toHaveCount(1)
  await page.keyboard.type('。')
  await page.keyboard.press('Control+z')
  await expect(editor).not.toContainText('[[')
  await expect(editor.locator('[data-reference-title]')).toHaveCount(1)
  await page.keyboard.press('Control+End'); await page.keyboard.press('Backspace')
  await expect(editor.locator('[data-reference-title]')).toHaveCount(0)
  await expect.poll(() => state.content).toBe('看')
})

test('undo restores the prose before a programmatic line break', async ({ page }) => {
  const state = await workspace(page)
  const editor = page.getByLabel('设定正文', { exact: true })
  await editor.fill('')
  await page.keyboard.type('A')
  await expect.poll(() => state.content).toBe('A')
  await page.keyboard.press('Enter')
  await expect.poll(() => state.content).toBe('A\n')
  await page.keyboard.press('Control+z')
  await expect.poll(() => state.content).toBe('A')
  await expect(editor).toHaveText('A')
  await page.keyboard.press('Control+Shift+z')
  await expect.poll(() => state.content).toBe('A\n')
  await page.keyboard.press('Control+z')
  await expect.poll(() => state.content).toBe('A')
  await page.keyboard.type('B')
  await expect.poll(() => state.content).toBe('AB')
  await page.keyboard.press('Control+Shift+z')
  await expect(editor).toHaveText('AB')
  await expect.poll(() => state.content).toBe('AB')
})

